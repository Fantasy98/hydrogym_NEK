#!/usr/bin/env bash
# Shared paths and defaults for the NACA0012 Re=200,000 zero-shot deployment.

source "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/common/settings.sh"
WING_PROJECT_ROOT="${ZS_ROOT}"
WING_CASE_DIR="${WING_CASE_DIR:-${ZS_ROOT}/2_naca0012_deploy}"

WING_IMAGE="${WING_IMAGE:-${ZS_IMAGE}}"
WING_NEK_MODULE="${WING_NEK_MODULE:-Nek5000/1.0-gompi-2024a-SystemCUDA-NACA0012}"
WING_PYTHON_VENV="${WING_PYTHON_VENV:-${ZS_PYTHON_VENV}}"

WING_HF_REPO="${WING_HF_REPO:-${ZS_HF_REPO}}"
WING_HF_REVISION="${WING_HF_REVISION:-${ZS_HF_REVISION}}"
WING_LOCAL_SOURCE="${WING_LOCAL_SOURCE:-}"
WING_SOURCE_PREPARED="${WING_SOURCE_PREPARED:-}"
WING_ENV_NAME="${WING_ENV_NAME:-NACA0012_3D_Re200000_AOA0}"
WING_DATA_ROOT="${WING_DATA_ROOT:-${WING_CASE_DIR}/data}"
WING_WORK_DIR="${WING_WORK_DIR:-${WING_CASE_DIR}/w}"
WING_CONFIG_DIR="${WING_CONFIG_DIR:-${WING_CASE_DIR}/config}"
WING_RUNTIME_CONFIG="${WING_RUNTIME_CONFIG:-${WING_CONFIG_DIR}/runtime.yml}"
WING_POLICY_TEMPLATE="${WING_POLICY_TEMPLATE:-${WING_CASE_DIR}/meta_policy_naca_wing.py}"
# Separate the fresh episode-40 experiment from the earlier JURECA runs.
WING_RUNS_DIR="${WING_RUNS_DIR:-${WING_CASE_DIR}/r40}"
WING_SOLVER_DIR="${WING_SOLVER_DIR:-${WING_RUNS_DIR}/s}"
# Optional seed for a NEW solver directory; ignored once initialized.
WING_RESTART_FROM="${WING_RESTART_FROM:-}"
WING_RESULTS_DIR="${WING_RESULTS_DIR:-${WING_CASE_DIR}/results40}"

# Keep the selected episode-40 policy across continuation jobs.
# An explicit WING_MODEL_STEP override selects a different exact checkpoint.
WING_TCF_CHECKPOINT_DIR="${WING_TCF_CHECKPOINT_DIR:-${ZS_ROOT}/1_tcf_train/run/checkpoints}"
WING_MODEL_STEP="${WING_MODEL_STEP:-576000000}"

WING_NPROC_NEK="${WING_NPROC_NEK:-4096}"
WING_TOTAL_RANKS=$((WING_NPROC_NEK + 1))
WING_NODES="${WING_NODES:-$(((WING_TOTAL_RANKS + ZS_CORES_PER_NODE - 1) / ZS_CORES_PER_NODE))}"
WING_TASKS_PER_NODE="${WING_TASKS_PER_NODE:-${ZS_CORES_PER_NODE}}"

# The standalone Python config requests 100,000 interactions and records every hundredth one.
# Limit controller runtime to 23.9 hours, leaving about six minutes for staging,
# archiving, initialization and shutdown within the 24-hour allocation.
WING_STEPS="${WING_STEPS:-}"
WING_RECORD_EVERY="${WING_RECORD_EVERY:-}"
WING_FLUSH_EVERY="${WING_FLUSH_EVERY:-100}"
WING_DEPLOY_SECONDS="${WING_DEPLOY_SECONDS:-86040}"
WING_MV_DATA="${WING_MV_DATA:-true}"

export WING_PROJECT_ROOT WING_CASE_DIR
export WING_IMAGE WING_NEK_MODULE WING_PYTHON_VENV
export WING_HF_REVISION WING_HF_REPO WING_ENV_NAME WING_DATA_ROOT WING_WORK_DIR
export WING_CONFIG_DIR WING_RUNTIME_CONFIG WING_POLICY_TEMPLATE WING_RUNS_DIR WING_RESULTS_DIR
export WING_SOLVER_DIR WING_RESTART_FROM
export WING_TCF_CHECKPOINT_DIR WING_MODEL_STEP
export WING_NPROC_NEK WING_TOTAL_RANKS WING_NODES WING_TASKS_PER_NODE
export WING_STEPS WING_RECORD_EVERY WING_FLUSH_EVERY WING_DEPLOY_SECONDS WING_MV_DATA

export WING_LOCAL_SOURCE WING_SOURCE_PREPARED
